<#
.SYNOPSIS
Wizard that customizes a default PSAppDeployToolkit 4.1.x Invoke-AppDeployToolkit.ps1.

.DESCRIPTION
Asks for app name, version, vendor, author, processes to close, installer (MSI or EXE),
install details and deferral settings, then edits the file:
  - Install   : MSI -> Start-ADTMsiProcess -Action Install ; EXE -> Start-ADTProcess
  - Uninstall : either Uninstall-ADTApplication -Name '<name>' (any version that matches)
                or the app's own uninstall command (UninstallString + silent switch)
  - Optional post-uninstall check: waits up to 60 s, then fails the deployment if the app
    is still detected (some uninstallers return before removal has finished).
  - Close-apps screen: 60-second countdown; optional deferrals on install.
Re-runnable: current values are shown in [brackets]; Enter keeps them, '-' clears an
optional value. Code generated by an earlier run is replaced, not duplicated.
A timestamped backup is created before writing.

DRAFT / UNTESTED end-to-end. Test on a non-production device first. Silent commands and
properties are stored in the script in clear text - do not include secrets.

.PARAMETER Path
Path to Invoke-AppDeployToolkit.ps1. Defaults to the one next to this script.
.PARAMETER NoBackup
Skip creating the backup copy.
#>
[CmdletBinding()]
param(
    [string]$Path = (Join-Path $PSScriptRoot 'Invoke-AppDeployToolkit.ps1'),
    [switch]$NoBackup
)

$ErrorActionPreference = 'Stop'
$Lit = "'(?:[^']|'')*'"     # regex for a single-quoted PowerShell literal

#region input helpers
function Read-WithDefault([string]$Prompt, [string]$Default) {
    do {
        $q = if ($Default) { "$Prompt [$Default]" } else { $Prompt }
        $v = (Read-Host $q).Trim()
        if (-not $v -and $Default) { $v = $Default }
    } while ([string]::IsNullOrWhiteSpace($v))
    $v
}
function Read-Optional([string]$Prompt, [string]$Default) {
    if ($Default) {
        $v = (Read-Host "$Prompt [$Default] (Enter=keep, -=clear)").Trim()
        if ($v -eq '-') { return '' }
        if ($v) { return $v }
        return $Default
    }
    (Read-Host "$Prompt (optional)").Trim()
}
function Read-YesNo([string]$Prompt, $Default = $null) {
    $hint = if ($Default -eq $true) { 'Y/n' } elseif ($Default -eq $false) { 'y/N' } else { 'y/n' }
    do {
        $v = (Read-Host "$Prompt ($hint)").Trim().ToLower()
        if (-not $v -and $null -ne $Default) { return [bool]$Default }
    } while ($v -notin 'y', 'n', 'yes', 'no')
    $v -in 'y', 'yes'
}
function Read-Choice([string]$Prompt, [string[]]$Valid, [string]$Default = '') {
    do {
        $q = if ($Default) { "$Prompt [$Default]" } else { $Prompt }
        $v = (Read-Host $q).Trim().ToLower()
        if (-not $v -and $Default) { $v = $Default }
    } while ($v -notin $Valid)
    $v
}
#endregion

#region text helpers
function ConvertTo-PsLiteral([string]$s) { "'" + $s.Replace("'", "''") + "'" }
function ConvertFrom-PsLiteral([string]$s) { $s.Trim().Substring(1, $s.Trim().Length - 2).Replace("''", "'") }
function Protect-Secrets([string]$s) {
    [regex]::Replace($s, '(?i)((?:pass(?:word)?|pwd|key|token|secret|license)\w*\s*=\s*)("[^"]*"|\S+)', '$1[REDACTED]')
}
function Split-CommandLine([string]$Cmd) { [regex]::Matches($Cmd, '"[^"]*"|\S+') | ForEach-Object { $_.Value } }
function Remove-Quotes([string]$s) { $s.Trim().Trim('"') }

function Get-FilePathExpression([string]$File) {
    $f = Remove-Quotes $File
    $systemExe = '^(cmd|powershell|pwsh|msiexec|reg|taskkill|wmic|sc|net|schtasks|wscript|cscript|rundll32|regsvr32|wusa|dism)(\.exe)?$'
    if ($f -match '%') { return "([System.Environment]::ExpandEnvironmentVariables($(ConvertTo-PsLiteral $f)))" }
    if ($f -match '[\\/:]' -or $f -match $systemExe) { return (ConvertTo-PsLiteral $f) }
    $safe = $f -replace '([`"$])', '`$1'                        # bare name -> package Files folder
    return '"$($adtSession.DirFiles)\' + $safe + '"'
}
function ConvertFrom-FilePathExpression([string]$Expr) {
    $e = $Expr.Trim()
    if ($e -match '^"\$\(\$adtSession\.DirFiles\)\\(.*)"$') { return ($Matches[1] -replace '`(.)', '$1') }
    if ($e -match '^\(\[System\.Environment\]::ExpandEnvironmentVariables\((.+)\)\)$') { return (ConvertFrom-PsLiteral $Matches[1]) }
    if ($e -match "^$Lit$") { return (ConvertFrom-PsLiteral $e) }
    $e
}
function ConvertFrom-ExeLine([string]$Line) {
    if ($Line -match "^\s*Start-ADTProcess -FilePath (.+?)(?: -ArgumentList ($Lit))?\s*$") {
        $f = ConvertFrom-FilePathExpression $Matches[1]
        if ($f -match '\s') { $f = '"' + $f + '"' }
        if ($Matches[2]) { return "$f $(ConvertFrom-PsLiteral $Matches[2])" }
        return $f
    }
    ''
}
#endregion

#region code builders
function New-ExeBlock([string]$Command, [string]$Header) {
    $tokens = @(Split-CommandLine $Command)
    if ($tokens.Count -eq 0) { throw 'Empty command.' }
    $argStr = if ($tokens.Count -gt 1) { ($tokens[1..($tokens.Count - 1)]) -join ' ' } else { '' }
    $line = "Start-ADTProcess -FilePath $(Get-FilePathExpression $tokens[0])"
    if ($argStr) { $line += " -ArgumentList $(ConvertTo-PsLiteral $argStr)" }
    @("    ## $Header - generated by wizard", "    $line")
}
function New-MsiInstallBlock([string]$File, [string]$ExtraArgs) {
    $line = "Start-ADTMsiProcess -Action Install -FilePath $(Get-FilePathExpression $File)"
    if ($ExtraArgs) { $line += " -AdditionalArgumentList $(ConvertTo-PsLiteral $ExtraArgs)" }
    @('    ## Install (MSI) - generated by wizard', "    $line")
}
function New-UninstallBlock([string]$Name) {
    @('    ## Uninstall (by application name) - generated by wizard',
      "    Uninstall-ADTApplication -Name $(ConvertTo-PsLiteral $Name)")
}
function New-VerifyBlock([string]$Name) {
    # Polls for up to ~60 s: some uninstallers (e.g. NSIS) return before the removal has finished.
    @('    ## Verify the app is gone (waits up to 60 s); fail the deployment if still detected - generated by wizard',
      '    $adtVerified = $false',
      '    for ($adtTry = 0; $adtTry -lt 12; $adtTry++)',
      '    {',
      "        if (-not (Get-ADTApplication -Name $(ConvertTo-PsLiteral $Name)))",
      '        {',
      '            $adtVerified = $true',
      '            break',
      '        }',
      '        Start-Sleep -Seconds 5',
      '    }',
      '    if (-not $adtVerified)',
      '    {',
      "        throw 'Uninstall verification failed: the application is still installed.'",
      '    }')
}
#endregion

#region file helpers
function Set-Pattern {
    param([ref]$Text, [string]$Pattern, [string]$Replacement, [string]$What, [switch]$All)
    $re = [regex]::new($Pattern)
    if (-not $re.IsMatch($Text.Value)) { throw "Template anchor not found: $What. Is this a stock PSADT 4.1.x file?" }
    $rep = [regex]::Replace($Replacement, '\$(?!\{\d\})', '$$$$')   # escape '$' except ${1}-style refs
    if ($All) { $Text.Value = $re.Replace($Text.Value, $rep) } else { $Text.Value = $re.Replace($Text.Value, $rep, 1) }
}
function Remove-GeneratedBlocks([string]$Text) {
    # Generated block = header comment containing 'generated by wizard' + following lines indented 4 or more spaces (nested lines such as '        throw ...' included).
    [regex]::Replace($Text, '(?m)^[ ]*## [^\r\n]*generated by wizard[^\r\n]*(?:\r?\n|\z)(?:[ ]{4,}\S[^\r\n]*(?:\r?\n|\z))*', '')
}
function Get-PreviousSettings([string]$Raw) {
    $p = @{}
    foreach ($k in 'Vendor', 'Name', 'Version') {
        $m = [regex]::Match($Raw, "(?m)^[ \t]*App$k = ($Lit)")
        if ($m.Success) { $p[$k] = ConvertFrom-PsLiteral $m.Groups[1].Value }
    }
    $m = [regex]::Match($Raw, "(?m)^[ \t]*AppScriptAuthor = ($Lit)")
    if ($m.Success) { $p.Author = ConvertFrom-PsLiteral $m.Groups[1].Value }

    $m = [regex]::Match($Raw, '(?m)^[ \t]*AppProcessesToClose = (@\([^\r\n]*\))')
    if ($m.Success) {
        $items = foreach ($t in [regex]::Matches($m.Groups[1].Value, "@\{[^}]*\}|$Lit")) {
            if ($t.Value.StartsWith('@{')) {
                $n = [regex]::Match($t.Value, "Name = ($Lit)").Groups[1].Value
                $d = [regex]::Match($t.Value, "Description = ($Lit)").Groups[1].Value
                if ($n) { if ($d) { "$(ConvertFrom-PsLiteral $n)|$(ConvertFrom-PsLiteral $d)" } else { ConvertFrom-PsLiteral $n } }
            }
            else { ConvertFrom-PsLiteral $t.Value }
        }
        $p.Processes = ($items -join ', ')
    }

    $m = [regex]::Match($Raw, '(?m)^[ \t]*AllowDefer = \$(true|false)')
    if ($m.Success) { $p.AllowDefer = ($m.Groups[1].Value -eq 'true') }
    $m = [regex]::Match($Raw, '(?m)^[ \t]*DeferTimes = (\d+)')
    if ($m.Success) { $p.DeferTimes = [int]$m.Groups[1].Value }

    $m = [regex]::Match($Raw, '(?m)^[ ]*## Install \((MSI|EXE)\)[^\r\n]*generated by wizard[^\r\n]*\r?\n[ ]*([^\r\n]+)')
    if ($m.Success) {
        $p.InstallType = $m.Groups[1].Value
        $line = $m.Groups[2].Value
        if ($p.InstallType -eq 'MSI') {
            $mm = [regex]::Match($line, "^Start-ADTMsiProcess -Action Install -FilePath (.+?)(?: -AdditionalArgumentList ($Lit))?\s*$")
            if ($mm.Success) {
                $p.InstallFile = ConvertFrom-FilePathExpression $mm.Groups[1].Value
                if ($mm.Groups[2].Value) { $p.InstallArgs = ConvertFrom-PsLiteral $mm.Groups[2].Value }
            }
        }
        else { $p.InstallCmd = ConvertFrom-ExeLine $line }
    }

    $m = [regex]::Match($Raw, "(?m)^[ ]*Uninstall-ADTApplication -Name ($Lit)")
    if ($m.Success) { $p.UninstallKind = 'name'; $p.UninstallName = ConvertFrom-PsLiteral $m.Groups[1].Value }
    $m = [regex]::Match($Raw, '(?m)^[ ]*## Uninstall \(command\)[^\r\n]*generated by wizard[^\r\n]*\r?\n[ ]*([^\r\n]+)')
    if ($m.Success) { $p.UninstallKind = 'cmd'; $p.UninstallCmd = ConvertFrom-ExeLine $m.Groups[1].Value }
    $p.HadVerify = [regex]::IsMatch($Raw, '(?m)^[ ]*## Verify the app is gone[^\r\n]*generated by wizard')
    $m = [regex]::Match($Raw, "(?s)## Verify the app is gone.*?Get-ADTApplication -Name ($Lit)")
    if ($m.Success) { $p.VerifyName = ConvertFrom-PsLiteral $m.Groups[1].Value }
    $p
}
function Get-InstalledAppEntries([string]$Keyword) {
    # Informational (Windows): installed apps whose DisplayName contains $Keyword.
    $paths = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall', 'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall', 'HKCU:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall'
    foreach ($b in $paths) {
        if (-not (Test-Path -LiteralPath $b)) { continue }
        foreach ($k in (Get-ChildItem -LiteralPath $b -ErrorAction SilentlyContinue)) {
            $p = Get-ItemProperty -LiteralPath $k.PSPath -ErrorAction SilentlyContinue
            if ($p -and $p.DisplayName -and $p.DisplayName -like "*$Keyword*") {
                [pscustomobject]@{ DisplayName = [string]$p.DisplayName; DisplayVersion = [string]$p.DisplayVersion; UninstallString = [string]$p.UninstallString; QuietUninstallString = [string]$p.QuietUninstallString; InstallLocation = [string]$p.InstallLocation; KeyPath = [string]$k.Name }
            }
        }
    }
}
#endregion

#region 1. review file
if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { throw "File not found: $Path" }
$raw = [System.IO.File]::ReadAllText($Path)
$nl = if ($raw -match "`r`n") { "`r`n" } else { "`n" }

Write-Host "`n== Reviewing $Path ==" -ForegroundColor Cyan
$ver = [regex]::Match($raw, "DeployAppScriptVersion = '([^']+)'").Groups[1].Value
Write-Host "Template version : $(if ($ver) { $ver } else { 'unknown' })"
if ($ver -and $ver -notmatch '^4\.1\.') { Write-Warning "Designed for PSADT 4.1.x; found $ver." }

$anchors = [ordered]@{
    'AppVendor'             = "(?m)^[ \t]*AppVendor = '"
    'AppName'               = "(?m)^[ \t]*AppName = '"
    'AppVersion'            = "(?m)^[ \t]*AppVersion = '"
    'AppScriptDate'         = "(?m)^[ \t]*AppScriptDate = '"
    'AppScriptAuthor'       = "(?m)^[ \t]*AppScriptAuthor = '"
    'AppProcessesToClose'   = '(?m)^[ \t]*AppProcessesToClose = @\('
    'Welcome params'        = '(?s)\$saiwParams = @\{.*?\}'
    'Install marker'        = '## <Perform Installation tasks here>'
    'Uninstall marker'      = '## <Perform Uninstallation tasks here>'
    'Post-uninstall marker' = '## <Perform Post-Uninstallation tasks here>'
}
$missing = @($anchors.Keys | Where-Object { $raw -notmatch $anchors[$_] })
foreach ($k in $anchors.Keys) { Write-Host ("  [{0}] {1}" -f $(if ($k -in $missing) { 'MISSING' } else { 'ok' }), $k) }
if ($missing) { throw "Template does not match expected 4.1.x layout (missing: $($missing -join ', '))." }

$prev = @{}
if ([regex]::IsMatch($raw, "(?m)^[ \t]*AppName = '[^']+'")) {
    $prev = Get-PreviousSettings $raw
    Write-Host "`nExisting settings found. Press Enter to keep the value in [brackets], or type a new one." -ForegroundColor Yellow
}
#endregion

#region 2. wizard
Write-Host "`n== App details ==" -ForegroundColor Cyan
$appName = Read-WithDefault 'App name' $prev.Name
$appVersion = Read-WithDefault 'App version' $prev.Version
$appVendor = Read-WithDefault 'App vendor' $prev.Vendor
$appAuthor = Read-WithDefault 'Script author' $prev.Author

Write-Host "`nProcesses to check and close (install AND uninstall; 60 s countdown)." -ForegroundColor Cyan
Write-Host 'Comma-separated, no .exe. Optional description: name|Description.'
$procInput = Read-Optional 'Processes' $prev.Processes
$procEntries = @()
if ($procInput) {
    foreach ($p in ($procInput -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ })) {
        $n, $d = $p -split '\|', 2
        $n = ($n.Trim() -replace '\.exe$', '')
        if ($d) { $procEntries += "@{ Name = $(ConvertTo-PsLiteral $n); Description = $(ConvertTo-PsLiteral $d.Trim()) }" }
        else { $procEntries += (ConvertTo-PsLiteral $n) }
    }
}

Write-Host "`n== Install ==" -ForegroundColor Cyan
$defType = switch ($prev.InstallType) { 'MSI' { '1' } 'EXE' { '2' } default { '' } }
$isMsi = (Read-Choice 'Installer type: 1) MSI  2) EXE' @('1', '2', 'msi', 'exe') $defType) -in '1', 'msi'
$sameType = $prev.InstallType -eq $(if ($isMsi) { 'MSI' } else { 'EXE' })
if ($isMsi) {
    Write-Host 'MSI file name is assumed to be in the package "Files" folder (or give a full path).'
    $msiFile = Read-WithDefault 'MSI file name (e.g. app.msi)' $(if ($sameType) { $prev.InstallFile } else { '' })
    $msiArgs = Read-Optional 'Extra install properties (e.g. ALLUSERS=1; /qn is added by PSADT)' $(if ($sameType) { $prev.InstallArgs } else { '' })
    $installBlock = New-MsiInstallBlock -File $msiFile -ExtraArgs $msiArgs
}
else {
    Write-Host 'Example: setup.exe /S   (bare file names are assumed to be in the "Files" folder)'
    $installBlock = New-ExeBlock (Read-WithDefault 'Silent INSTALL command' $(if ($sameType) { $prev.InstallCmd } else { '' })) 'Install (EXE)'
}

Write-Host "`n== Uninstall ==" -ForegroundColor Cyan
Write-Host 'Method: 1) Application name (Uninstall-ADTApplication, matches any version)'
Write-Host '        2) Uninstall command (the app''s UninstallString + silent switch)'
$um = Read-Choice 'Choose 1-2' @('1', '2') $(if ($prev.UninstallKind -eq 'cmd') { '2' } else { '1' })

if ($um -eq '1') {
    Write-Host 'Use the base name (no version) so every version matches.'
    $uninstName = Read-WithDefault 'Application name to uninstall' $(if ($prev.UninstallName) { $prev.UninstallName } else { $appName })
    if ($env:OS -eq 'Windows_NT') {
        $hits = @(Get-InstalledAppEntries $uninstName | ForEach-Object { $_.DisplayName } | Select-Object -Unique)
        if ($hits.Count -eq 0) { Write-Host "  (nothing on this machine currently matches '$uninstName')" -ForegroundColor DarkGray }
        else { Write-Host "  On this machine '$uninstName' matches: $($hits -join '; ')" -ForegroundColor DarkGray }
    }
    $uninstallBlock = New-UninstallBlock $uninstName
    $detectName = $uninstName
}
else {
    $defCmd = $prev.UninstallCmd
    if ($env:OS -eq 'Windows_NT') {
        $kw = Read-WithDefault 'Search installed apps for (to read their UninstallString)' $appName
        $entries = @(Get-InstalledAppEntries $kw | Where-Object { $_.UninstallString -or $_.QuietUninstallString })
        foreach ($e in $entries) {
            Write-Host "  $($e.DisplayName)" -ForegroundColor DarkGray
            if ($e.QuietUninstallString) { Write-Host "      QuietUninstallString: $($e.QuietUninstallString)" -ForegroundColor DarkGray }
            if ($e.UninstallString) { Write-Host "      UninstallString     : $($e.UninstallString)" -ForegroundColor DarkGray }
        }
        if (-not $defCmd -and $entries.Count -gt 0) { $defCmd = if ($entries[0].QuietUninstallString) { $entries[0].QuietUninstallString } else { $entries[0].UninstallString } }
    }
    Write-Host 'Add the silent switch yourself (e.g. /S for NSIS, /VERYSILENT for Inno, /qn for msiexec). Example: "C:\Program Files\App\uninstall.exe" /S'
    $cmd = Read-WithDefault 'Silent UNINSTALL command' $defCmd
    $uninstallBlock = New-ExeBlock $cmd 'Uninstall (command)'
    $detectName = Read-WithDefault 'Application name used to verify removal (contains match)' $(if ($prev.VerifyName) { $prev.VerifyName } else { $appName })
}
$wantVerify = Read-YesNo 'Fail the deployment if the app is still installed after uninstall (waits up to 60 s)?' $(if ($prev.Count -gt 0) { $prev.HadVerify } else { $true })
$verifyBlock = if ($wantVerify) { New-VerifyBlock $detectName } else { $null }

Write-Host "`n== Deferral ==" -ForegroundColor Cyan
$allowDefer = Read-YesNo 'Allow user to defer the install?' $(if ($null -ne $prev.AllowDefer) { $prev.AllowDefer } else { $null })
$deferTimes = 0
if ($allowDefer) {
    $defN = if ($prev.DeferTimes) { [string]$prev.DeferTimes } else { '' }
    do { $s = Read-WithDefault 'How many deferrals' $defN } while (-not ([int]::TryParse($s, [ref]$deferTimes) -and $deferTimes -ge 1))
}

Write-Host "`n== Summary ==" -ForegroundColor Cyan
Write-Host "App            : $appVendor $appName $appVersion (author: $appAuthor)"
Write-Host "Close processes: $(if ($procEntries) { $procInput } else { '(none)' })  [60 s countdown]"
Write-Host "Deferral       : $(if ($allowDefer) { "allowed, $deferTimes time(s)" } else { 'not allowed' })"
Write-Host 'Install code   :';   $installBlock   | ForEach-Object { Write-Host (Protect-Secrets $_) }
Write-Host 'Uninstall code :';   $uninstallBlock | ForEach-Object { Write-Host $_ }
if ($verifyBlock) { Write-Host 'Verification   :'; $verifyBlock | ForEach-Object { Write-Host $_ } }
if (-not (Read-YesNo "`nApply these changes to the file?" $true)) { Write-Host 'Cancelled. No changes made.'; return }
#endregion

#region 3. modify
$t = Remove-GeneratedBlocks $raw        # drop code generated by a previous wizard run
Set-Pattern ([ref]$t) '(?m)^([ \t]*AppVendor = )[^\r\n]*'       ('${1}' + (ConvertTo-PsLiteral $appVendor))  'AppVendor'
Set-Pattern ([ref]$t) '(?m)^([ \t]*AppName = )[^\r\n]*'         ('${1}' + (ConvertTo-PsLiteral $appName))    'AppName'
Set-Pattern ([ref]$t) '(?m)^([ \t]*AppVersion = )[^\r\n]*'      ('${1}' + (ConvertTo-PsLiteral $appVersion)) 'AppVersion'
Set-Pattern ([ref]$t) '(?m)^([ \t]*AppScriptAuthor = )[^\r\n]*' ('${1}' + (ConvertTo-PsLiteral $appAuthor))  'AppScriptAuthor'
Set-Pattern ([ref]$t) '(?m)^([ \t]*AppScriptDate = )[^\r\n]*'   ('${1}' + (ConvertTo-PsLiteral (Get-Date -Format 'yyyy-MM-dd'))) 'AppScriptDate'

$procArray = if ($procEntries) { '@(' + ($procEntries -join ', ') + ')' } else { '@()' }
Set-Pattern ([ref]$t) '(?m)^([ \t]*AppProcessesToClose = )[^\r\n]*' ('${1}' + $procArray) 'AppProcessesToClose'

# Deferral: AllowDefer line always kept; DeferTimes line added/updated/removed as needed.
if ($allowDefer) {
    Set-Pattern ([ref]$t) '(?m)^([ \t]*AllowDefer = )[^\r\n]*' '${1}$true' 'AllowDefer'
    if ($t -match '(?m)^[ \t]*DeferTimes = ') {
        Set-Pattern ([ref]$t) '(?m)^([ \t]*DeferTimes = )[^\r\n]*' ('${1}' + $deferTimes) 'DeferTimes'
    }
    else {
        Set-Pattern ([ref]$t) '(?m)^([ \t]*)(AllowDefer = [^\r\n]*)' ('${1}${2}' + $nl + '${1}DeferTimes = ' + $deferTimes) 'DeferTimes (insert)'
    }
}
else {
    Set-Pattern ([ref]$t) '(?m)^([ \t]*AllowDefer = )[^\r\n]*' '${1}$false' 'AllowDefer'
    $t = [regex]::Replace($t, '(?m)^[ \t]*DeferTimes = [^\r\n]*\r?\n', '')
}

# 60 s close-apps countdown (uninstall/repair already have it; add to install once).
Set-Pattern ([ref]$t) '-CloseProcessesCountdown \d+' '-CloseProcessesCountdown 60' 'Uninstall/Repair countdown' -All
if ($t -notmatch "CloseProcessesCountdown', 60") {
    Set-Pattern ([ref]$t) "(?m)^([ \t]*)(\`$saiwParams\.Add\('CloseProcesses', \`$adtSession\.AppProcessesToClose\))" `
        ('${1}${2}' + $nl + '${1}$saiwParams.Add(''CloseProcessesCountdown'', 60)') 'Install CloseProcesses'
}

Set-Pattern ([ref]$t) '(## <Perform Installation tasks here>)'   ('${1}' + $nl + ($installBlock -join $nl))   'Install marker'
Set-Pattern ([ref]$t) '(## <Perform Uninstallation tasks here>)' ('${1}' + $nl + ($uninstallBlock -join $nl)) 'Uninstall marker'
if ($verifyBlock) {
    Set-Pattern ([ref]$t) '(## <Perform Post-Uninstallation tasks here>)' ('${1}' + $nl + ($verifyBlock -join $nl)) 'Post-uninstall marker'
}

# Sample end-of-install prompt would block silent deployments: comment it out.
$t = [regex]::Replace($t, "(?m)^([ \t]*)(Show-ADTInstallationPrompt -Message 'You can customize text to appear at the end of an install[^\r\n]*)", '${1}# ${2}')

$errs = $null
[void][System.Management.Automation.Language.Parser]::ParseInput($t, [ref]$null, [ref]$errs)
if ($errs -and $errs.Count) { throw "Generated script has syntax errors, nothing written: $($errs[0].Message) (line $($errs[0].Extent.StartLineNumber))" }

if (-not $NoBackup) {
    $bak = "$Path.bak-$(Get-Date -Format yyyyMMddHHmmss)"
    Copy-Item -LiteralPath $Path -Destination $bak
    Write-Host "Backup: $bak"
}
[System.IO.File]::WriteAllText($Path, $t, (New-Object System.Text.UTF8Encoding($true)))
Write-Host "Updated: $Path" -ForegroundColor Green
Write-Host 'Next: review the file, then test with  powershell.exe -File Invoke-AppDeployToolkit.ps1 -DeploymentType Uninstall' -ForegroundColor Yellow
#endregion

#region 4. suggested UEM detection criteria
Write-Host "`n== Suggested UEM detection / 'install complete' criteria ==" -ForegroundColor Cyan
Write-Host 'Use a VERSION-based rule so an older, manually installed copy is NOT treated as already installed.'
$local = @()
if ($env:OS -eq 'Windows_NT') { $local = @(Get-InstalledAppEntries $detectName | Where-Object { $_.KeyPath -like 'HKEY_LOCAL_MACHINE*' }) }
if ($local.Count -gt 0) {
    $e = $local[0]
    Write-Host "`nRegistry rule (read from this machine: $($e.DisplayName)):"
    Write-Host "  Key       : $($e.KeyPath)"
    Write-Host '  Value     : DisplayVersion'
    Write-Host "  Condition : greater than or equal to $appVersion   (if your console only offers 'equals', use the exact version)"
    if ($e.KeyPath -like '*WOW6432Node*') { Write-Host '  Note      : key is in the 32-bit registry view (WOW6432Node).' -ForegroundColor DarkGray }
    if ($e.DisplayVersion -and $e.DisplayVersion -ne $appVersion) {
        Write-Host "  Note      : this machine has DisplayVersion '$($e.DisplayVersion)' but you packaged '$appVersion'. After installing the package, confirm the NEW install writes exactly '$appVersion' (same format)." -ForegroundColor Yellow
    }
    $dir = if ($e.InstallLocation) { $e.InstallLocation.Trim('"') } elseif ($e.UninstallString -match '^\s*"?([^"]+?\.exe)') { Split-Path $Matches[1] } else { '' }
    if ($dir) {
        Write-Host "`nFile rule (alternative):"
        Write-Host "  Path      : $dir\<main exe>   (pick the app's main .exe)"
        Write-Host "  Condition : file version greater than or equal to $appVersion"
        Write-Host '  Check     : (Get-Item "<path>").VersionInfo.FileVersion  - make sure its format matches the version above.'
    }
}
else {
    Write-Host "`nRegistry rule (template - nothing matching '$detectName' is installed on this machine):"
    Write-Host '  Key       : HKEY_LOCAL_MACHINE\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\<key name>'
    Write-Host '  Value     : DisplayVersion'
    Write-Host "  Condition : greater than or equal to $appVersion"
    Write-Host '  Find <key name> on a machine with the app installed:'
    Write-Host "    Get-ItemProperty 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*' | Where-Object DisplayName -like '*$detectName*' | Select-Object PSChildName, DisplayName, DisplayVersion"
}
if ($isMsi) { Write-Host "`nMSI: UEM can also detect by the MSI ProductCode, but that is per version - the registry rule above is simpler to maintain." -ForegroundColor DarkGray }
Write-Host "`nUse the same rule for 'When to call install complete' so Hub reports success only when the new version is really installed." -ForegroundColor Yellow
